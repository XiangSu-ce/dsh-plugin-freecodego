/**
 * Generate the bundle's agent-preset patches from the plugin's preset assets.
 *
 * Why this exists
 * ---------------
 * Harness 0.1.7 replaced the `.agent-presets/` directory roster with declared
 * presets: a profile's composition carries one `@deepseek-ai/dsh-agent-preset`
 * row per preset, and the official bundles ship those rows as patch files —
 * `packages/bundle/web-app/presets/*.patch.yml`, listed in `dsh.bundle.patch`.
 * Declaring our two modes that way is the form that makes them ordinary roster
 * rows: the Web editor can override `config.plugins` by id, and the registry
 * audits them exactly like the shipped ones.
 *
 * A patch cannot include another file (`vendor/include` applies patch *lists* to
 * entry lists, not YAML to YAML), so the rows have to be written out here. The
 * plugin's assets stay the single source: this script copies `agent.cordis.yml`
 * verbatim — comments and `!!js` rows included — so the two can only drift if
 * this script is not run, which `--check` turns into a failure.
 *
 * The output is inert until `packages/freecodego/bundle-latest/package.json`
 * lists the files in `dsh.bundle.patch`.
 *
 * Usage:
 *   node scripts/gen-preset-patches.mjs           # write
 *   node scripts/gen-preset-patches.mjs --check   # fail when stale
 *
 * @module scripts/gen-preset-patches
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')

/** The plugin package that owns the preset assets. */
const ASSET_ROOT = join(ROOT, 'packages', 'freecodego', 'harness-plugin', 'assets', 'presets')

/** The bundle package the patches are written into. */
const PATCH_ROOT = join(ROOT, 'packages', 'freecodego', 'bundle-latest', 'presets')

/** Preset ids to emit, in roster order — mirrors `BUNDLED_PRESET_IDS` in the plugin. */
const PRESET_IDS = ['freecodego', 'augmentcode']

/** The composition file a preset directory is made of. */
const COMPOSITION_FILE = 'agent.cordis.yml'

/** The metadata file carrying the roster copy. */
const METADATA_FILE = 'preset.yml'

/** The declaring plugin each patch row mounts. */
const DECLARATION = '@deepseek-ai/dsh-agent-preset'

/** Indentation of the composition rows under `        plugins:`. */
const ROW_INDENT = '          '

/** Relative path for a message, in the repository's own slash form. */
const relative = path => path.replace(ROOT, '').split(sep).join('/')

/**
 * Read one `key: value` line from a preset's metadata file.
 *
 * Deliberately not a YAML load: the file is a flat, three-field document, and a
 * loader here would need the `!!js` type the composition owns. Values are
 * double-quoted by the writer, so it never depends on how the asset quotes them.
 * @param source - the metadata file's text.
 * @param key - the field to read.
 * @returns the raw value, or `undefined` when the field is absent.
 */
function metadataValue(source, key) {
  const match = new RegExp(`^${key}:[ \\t]*(.*)$`, 'm').exec(source)
  const value = match?.[1]?.trim()
  return value === undefined || value === '' ? undefined : value
}

/**
 * The patch file one preset id produces.
 * @param presetId - the preset id.
 * @returns the file's exact text.
 * @throws when the bundled asset is missing.
 */
function emit(presetId) {
  const directory = join(ASSET_ROOT, presetId)
  const compositionPath = join(directory, COMPOSITION_FILE)
  const metadataPath = join(directory, METADATA_FILE)
  if (!existsSync(compositionPath) || !existsSync(metadataPath)) {
    throw new Error(`missing bundled preset asset: ${compositionPath}`)
  }
  const metadata = readFileSync(metadataPath, 'utf8')
  const name = metadataValue(metadata, 'name')
  const description = metadataValue(metadata, 'description')
  const order = metadataValue(metadata, 'order')
  const rows = readFileSync(compositionPath, 'utf8').replace(/\r\n/g, '\n').replace(/\n+$/, '')
  const lines = [
    '# Generated by scripts/gen-preset-patches.mjs — do not edit by hand.',
    '#',
    `# The FreeCodeGo plugin's \`${presetId}\` mode, declared the way the harness reads`,
    `# a roster: one \`${DECLARATION}\` row whose \`config.plugins\` is the`,
    '# plugin\'s own bundled composition, copied verbatim.',
    '#',
    '# Inert until `dsh.bundle.patch` in this package\'s manifest lists this file.',
    '# Meanwhile the plugin declares the same preset through `ctx.agentPresets` at',
    '# boot, and skips it as soon as a deployment declares it here.',
    '- insert:',
    `    - id: preset-${presetId}`,
    `      name: '${DECLARATION}'`,
    '      config:',
    `        id: ${presetId}`,
  ]
  if (name !== undefined) lines.push(`        name: ${JSON.stringify(name)}`)
  if (description !== undefined) lines.push(`        description: ${JSON.stringify(description)}`)
  if (order !== undefined) lines.push(`        order: ${order}`)
  lines.push('        plugins:')
  for (const row of rows.split('\n')) lines.push(row === '' ? '' : `${ROW_INDENT}${row}`)
  lines.push('')
  return lines.join('\n')
}

/** Every patch file this script owns, as `[path, text]`. */
function plan() {
  return PRESET_IDS.map(presetId => [join(PATCH_ROOT, `${presetId}.patch.yml`), emit(presetId)])
}

const check = process.argv.includes('--check')
const stale = []
for (const [path, text] of plan()) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : undefined
  if (current === text) continue
  if (check) {
    stale.push(relative(path))
    continue
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, text)
  process.stdout.write(`gen-preset-patches: wrote ${relative(path)}\n`)
}
if (check && stale.length > 0) {
  process.stderr.write('gen-preset-patches: these patch files are stale; run `pnpm run gen-preset-patches`:\n')
  for (const path of stale) process.stderr.write(`  ${path}\n`)
  process.exit(1)
}
if (check) process.stdout.write('gen-preset-patches: agent-preset patches are up to date.\n')
